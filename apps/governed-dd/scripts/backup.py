"""Offline volume archive encryption/checksum tool, run in transient container."""
import argparse
import hashlib
import json
import os
import tarfile
from pathlib import Path
from cryptography.fernet import Fernet
import base64

p=argparse.ArgumentParser();p.add_argument('action',choices=['pack','restore','verify','list']);a=p.parse_args()
key=base64.urlsafe_b64encode(hashlib.sha256(Path('/key').read_bytes()).digest());cipher=Fernet(key)
root=Path('/backup')
if a.action=='pack':
 manifest={}
 sources=list(Path('/volumes').iterdir())
 if Path('/configuration').exists():sources.append(Path('/configuration'))
 for source in sources:
  archive=root/(source.name+'.tar')
  with tarfile.open(archive,'w') as bundle:
   if source.name=='configuration':
    # Runtime state is in volumes. Include only the private configuration needed to recover it.
    for relative in ['.env','local/secrets','local/tenants','local/versions.json','local/realm.json','local/control-init.sql','local/control.compose.yaml','local/workstation-public-ca.pem']:
     path=source/relative
     if path.exists():bundle.add(path,arcname='data/'+relative)
   else:bundle.add(source,arcname='data')
  data=archive.read_bytes();manifest[source.name]=hashlib.sha256(data).hexdigest()
  (root/(source.name+'.enc')).write_bytes(cipher.encrypt(data));archive.unlink()
 (root/'manifest.enc').write_bytes(cipher.encrypt(json.dumps(manifest).encode()))
 print('Encrypted offline volume backup complete; no plaintext manifest.')
else:
 manifest=json.loads(cipher.decrypt((root/'manifest.enc').read_bytes()))
 if a.action=='list':
  print(json.dumps(list(manifest)));raise SystemExit(0)
 for name,digest in manifest.items():
  data=cipher.decrypt((root/(name+'.enc')).read_bytes())
  if hashlib.sha256(data).hexdigest()!=digest:raise ValueError('Archive checksum mismatch')
  if a.action=='restore':
   import io
   target=Path('/volumes')/name
   if any(target.iterdir()):raise ValueError('Restore target must be empty')
   with tarfile.open(fileobj=io.BytesIO(data)) as bundle:
    for member in bundle.getmembers():
     if member.name=='data':
      os.chown(target,member.uid,member.gid);os.chmod(target,member.mode & 0o777)
      continue
     if not member.name.startswith('data/'):raise ValueError('Unexpected archive root')
     member.name=member.name[5:]
     if member.issym() and member.linkname.startswith('/'):
      # Pinned upstream skills point at immutable image assets, not engagement data.
      # They are regenerated by Paperclip; never restore arbitrary absolute links.
      if '/skills/' in member.name and member.linkname.startswith('/app/skills/'):
       continue
      if '/codex/home/tmp/arg0/' in member.name and member.linkname=='/usr/local/lib/node_modules/@openai/codex/node_modules/@openai/codex-linux-x64/vendor/x86_64-unknown-linux-musl/bin/codex' and Path(member.name).name in ('apply_patch','applypatch','codex-execve-wrapper','codex-linux-sandbox'):
       continue  # Pinned CLI regenerates these temporary executable aliases.
      raise ValueError('Unexpected absolute backup link')
     # Validate traversal/link destinations, then retain numeric ownership for databases and Git.
     checked=tarfile.data_filter(member,str(target))
     if checked is None:raise ValueError('Unsafe backup entry')
     checked.uid,checked.gid=member.uid,member.gid
     bundle.extract(checked,target,filter='fully_trusted',numeric_owner=True)
 print('All encrypted archive checksums verified.')
